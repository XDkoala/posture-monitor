let language: Language = readInitialLanguage();

function readInitialLanguage(): Language {
  try {
    const stored = typeof localStorage === 'undefined' ? null : localStorage.getItem(LANGUAGE_KEY);
    if (stored === 'zh-CN' || stored === 'en') return stored;
  } catch {
    // Storage can be unavailable in restricted browser contexts.
  }
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function getLanguage(): Language {
  return language;
}

export function setLanguage(next: Language): void {
  language = next;
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(LANGUAGE_KEY, next);
  } catch {
    // The current session can still switch languages without persistence.
  }
}

export function t(key: TranslationKey, params: Record<string, string | number> = {}): string {
  const template = (language === 'zh-CN' ? zh : en)[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

export function applyDocumentTranslations(root: ParentNode = document): void {
  document.documentElement.lang = language;
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n as TranslationKey);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAria as TranslationKey));
  });
  const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
  if (description) description.content = t('meta.description');
}
